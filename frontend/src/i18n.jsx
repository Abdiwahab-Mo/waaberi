const read = () => { try { const l = localStorage.getItem("wlang"); return T[l] ? l : DEFAULT; } catch { return DEFAULT; } };
const Ctx = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(read);
  const setLang = (l) => { setLangState(l); try { localStorage.setItem("wlang", l); } catch { /* private mode */ } };
  return <Ctx.Provider value={{ lang, setLang }}>{children}</Ctx.Provider>;
}

export function useLang() {
  const { lang, setLang } = useContext(Ctx);
  const t = (key, vars) => {
    let s = T[lang][key] ?? T.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    return s;
  };
  const tErr = (msg) => (lang === "en" ? msg : SERVER[msg]?.[lang] || msg);
  // Admin-written content: use the translation if one exists, otherwise English
  const pick = (obj, field) => (lang !== "en" && obj?.i18n?.[lang]?.[field]) || obj?.[field] || "";
  const date = (d) => new Date(d).toLocaleDateString(lang === "ar" ? "ar" : lang === "so" ? "so-SO" : "en-GB", { year: "numeric", month: "long", day: "numeric" });
  return { lang, setLang, t, tErr, pick, date, dir: lang === "ar" ? "rtl" : "ltr" };
}

// Applies lang/dir to <html> for the public site (admin stays English, left-to-right)
export function useDocumentLang(lang, dir) {
  useEffect(() => {
    const h = document.documentElement;
    h.lang = lang; h.dir = dir;
    return () => { h.lang = "en"; h.dir = "ltr"; };
  }, [lang, dir]);
}
